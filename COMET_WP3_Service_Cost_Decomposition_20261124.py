#!/usr/bin/env python3
"""WP3 §6.1: derive defensible paired server service cost components from recorded
COMET common-gateway response timing. No experiment reruns. Read-only inputs.
Priors: response fields are generated by common_ingress/src/main.rs and
docker_adapter.rs. Output new CSV/JSON in research_enhancement/reports/.
"""
from pathlib import Path
import datetime as dt
import csv
import json
import math
import statistics
from collections import defaultdict

ROOT=Path(__file__).resolve().parent
SRC=ROOT/"research_enhancement/automated_supervisor_workplan/20261123_184837_1364620"
OUT=ROOT/"research_enhancement/reports/wp3_service_decomposition"/dt.datetime.now(dt.timezone.utc).strftime('%Y%m%d_%H%M%S')
OUT.mkdir(parents=True,exist_ok=False)

def num(v):
    return type(v) in (int,float) and math.isfinite(v) and v>=0

def nested_fields(obj):
    """Recover response timing fields in supported nested response representations.
    Reject ambiguously inconsistent duplicates rather than choose a convenient value.
    """
    names=("request_total_ns","inference_time_ns","execution_time_ns","adapter_roundtrip_ns")
    found={}
    def walk(x,depth=0):
        if depth>5:return
        if isinstance(x,dict):
            for n in names:
                v=x.get(n)
                if num(v):
                    found.setdefault(n,set()).add(int(v))
            for k,v in x.items():
                if k in ("response","response_body","body","result","server_response","payload","inference_response") and isinstance(v,(dict,list)):
                    walk(v,depth+1)
        elif isinstance(x,list):
            for y in x[:3]:
                if isinstance(y,dict):walk(y,depth+1)
    walk(obj)
    # Nested response may be a JSON string; only parse conventional keys.
    for k in ("response","response_body","body","result","server_response"):
        v=obj.get(k) if isinstance(obj,dict) else None
        if isinstance(v,str) and len(v)<20000:
            try: walk(json.loads(v),1)
            except (ValueError,TypeError): pass
    if any(len(v)>1 for v in found.values()):return None,"CONFLICTING_TIMING_FIELDS"
    return {k:next(iter(v)) for k,v in found.items()},None

def quantile(a,q):
    if not a:return None
    s=sorted(a)
    return s[math.ceil((len(s)-1)*q)]

def describe(a):
    if not a:return None
    return {"n":len(a),"mean_ns":round(statistics.mean(a),3),
            "median_ns":quantile(a,.5),"p95_ns":quantile(a,.95),
            "p99_ns":quantile(a,.99),"mean_ms":round(statistics.mean(a)/1e6,8)}

report={"scope":"WP3 §6.1 paired complete backend service decomposition from recorded gateway response fields",
        "source":str(SRC),"created_utc":dt.datetime.now(dt.timezone.utc).isoformat(),
        "models":{},"interpretation":{
          "request_total_ns":"Gateway request-handler elapsed time, excludes client-side HTTP and scheduling time",
          "inference_time_ns":"Backend-specific inference window reported by backend or Wasm adapter",
          "execution_time_ns":"Backend-reported isolated model execution window",
          "adapter_roundtrip_ns":"Docker adapter outbound HTTP request and response duration",
          "wasmtime_gateway_overhead":"request_total_ns - inference_time_ns, includes gateway and spawn-blocking scheduling outside inference window",
          "wasmtime_nonexecution_inference":"inference_time_ns - execution_time_ns, includes lock waiting and input conversion/copy; NOT pure memory-copy time",
          "docker_gateway_overhead":"request_total_ns - adapter_roundtrip_ns, gateway handling outside Docker adapter",
          "docker_adapter_noninference":"adapter_roundtrip_ns - inference_time_ns, includes network/HTTP and backend handling outside backend inference window",
          "docker_inference_nonexecution":"inference_time_ns - execution_time_ns, backend overhead within inference window",
          "kernel_batched":"Use separately measured WP3 batched kernel results for pure native/Wasm guest and copy isolation; these response fields do not replace them"},
        "limits":["No negative residuals retained as valid components; invalid ordering is counted",
                  "These decomposition terms are elapsed times of nested spans, not independent additive CPU consumption",
                  "Measured gateway server service cost is not the same as client-side end-to-end latency",
                  "Source-specific denominators vary: only complete response records enter paired decomposition",
                  "No invented corrected 2.5% significance; preserves observed measurements"],
        "go_decision":"NOT_AUTOMATICALLY_GRANTED"}
outrows=[]
for model in ("lr","rf"):
    for backend in ("wasmtime","docker"):
        folder=SRC/f"{model}_{backend}"
        prefix=f"{model}_{backend}"
        fields=("request_total_ns","inference_time_ns","execution_time_ns")
        if backend=="docker":fields+=("adapter_roundtrip_ns",)
        terms=defaultdict(list)
        counts=defaultdict(int)
        files=sorted(folder.glob("rps*_rep*.requests.jsonl"))
        for f in files:
            with f.open(errors="replace") as stream:
                for line in stream:
                    counts["records"]+=1
                    try:record=json.loads(line)
                    except (ValueError,TypeError):counts["malformed_json"]+=1;continue
                    if not isinstance(record,dict):counts["nonobject"]+=1;continue
                    vals,conflict=nested_fields(record)
                    if conflict:counts["conflicting"]+=1;continue
                    if not all(k in vals for k in fields):
                        counts["missing_required_response_fields"]+=1;continue
                    total=vals["request_total_ns"]
                    inf=vals["inference_time_ns"]
                    execution=vals["execution_time_ns"]
                    if backend=="wasmtime":
                        valid=total>=inf>=execution
                        components={
                            "gateway_outside_inference_ns":total-inf,
                            "inference_nonexecution_ns":inf-execution,
                            "isolated_execution_ns":execution}
                    else:
                        adapter=vals["adapter_roundtrip_ns"]
                        valid=total>=adapter>=inf>=execution
                        components={
                            "gateway_outside_adapter_ns":total-adapter,
                            "adapter_noninference_ns":adapter-inf,
                            "backend_inference_nonexecution_ns":inf-execution,
                            "isolated_execution_ns":execution}
                    if not valid:counts["invalid_nested_order"]+=1;continue
                    counts["valid_pairs"]+=1
                    for k,v in {**vals,**components}.items():terms[k].append(v)
        report["models"][prefix]={
            "source_files":len(files),"record_counts":dict(counts),
            "components":{k:describe(v) for k,v in sorted(terms.items())},
            "measurement_kind":"paired elapsed spans, no new experiment"}
        for k,v in sorted(terms.items()):
            s=describe(v)
            outrows.append({"model":model,"backend":backend,"component":k,**s})
        print(f"{prefix}: {counts['valid_pairs']} valid paired responses / {counts['records']} raw rows",
              f"; invalid order {counts['invalid_nested_order']}",
              f"; missing fields {counts['missing_required_response_fields']}")
if not any(x["record_counts"].get("valid_pairs") for x in report["models"].values()):
    print("NO COMPLETE PAIRED RECORDS; inspect schema; no GO asserted.")
with (OUT/"DECOMPOSITION.json").open("w") as f:json.dump(report,f,indent=2);f.write("\n")
with (OUT/"DECOMPOSITION.csv").open("w",newline="") as f:
    writer=csv.DictWriter(f,fieldnames=["model","backend","component","n","mean_ns","median_ns","p95_ns","p99_ns","mean_ms"])
    writer.writeheader();writer.writerows(outrows)
print("SAVED",OUT/"DECOMPOSITION.json")
print("WP3 service timing extracted; this does NOT by itself prove WP1-WP3 supervisor GO.")
